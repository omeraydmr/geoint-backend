async def create_mock_polygon(lon: float, lat: float, size: float = 0.05) -> MultiPolygon:
    """Create a small square polygon"""
    poly = Polygon([
        (lon - size, lat - size),
        (lon + size, lat - size),
        (lon + size, lat + size),
        (lon - size, lat + size),
        (lon - size, lat - size),
    ])
    return from_shape(MultiPolygon([poly]), srid=4326)

