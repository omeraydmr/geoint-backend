async def seed_districts():
    async with AsyncSessionLocal() as db:
        logger.info("🗑️ Deleting existing districts (to fix names/location)...")
        await db.execute(delete(District))
        await db.commit()
        
        logger.info("🌍 Seeding mock districts for existing provinces...")
        
        # Get all provinces
        result = await db.execute(select(Province))
        provinces = result.scalars().all()
        
        created_count = 0
        
        for province in provinces:
            # Get centroid
            if not province.centroid:
                continue
                
            centroid = to_shape(province.centroid)
            base_lon = centroid.x
            base_lat = centroid.y
            
            # Determine districts -- all 81 provinces have real data
            names = REAL_DISTRICTS.get(province.name)
            if not names:
                logger.warning(f"No district data for province: {province.name} (code={province.code}), skipping.")
                continue
            
            for i, name in enumerate(names):
                # Random offset around centroid (approx 0.1-0.3 degrees)
                # Use i to scatter them slightly deterministically or randomly
                lon_off = random.uniform(-0.2, 0.2)
                lat_off = random.uniform(-0.2, 0.2)
                
                d_lon = base_lon + lon_off
                d_lat = base_lat + lat_off
                
                geom = await create_mock_polygon(d_lon, d_lat)
                pt = from_shape(Point(d_lon, d_lat), srid=4326)
                
                district = District(
                    id=uuid.uuid4(),
                    province_id=province.id,
                    code=f"{province.code}-{str(i+1).zfill(2)}",
                    name=name,
                    population=10000,
                    area_km2=100,
                    geom=geom,
                    centroid=pt,
                    created_at=datetime.utcnow(),
                    updated_at=datetime.utcnow()
                )
                db.add(district)
                created_count += 1
            
            # Commit per province
            await db.commit()
            logger.info(f"✅ Created {len(names)} districts for {province.name}")
            
        logger.info(f"🎉 Completed! Created: {created_count}")

if __name__ == "__main__":
    asyncio.run(seed_districts())
